// MARK: - Configuration

struct AIServiceConfiguration {
    let apiKey: String
    let model: String

    static let current = AIServiceConfiguration(
        apiKey: Bundle.main.aiString(for: "OpenAIAPIKey") ?? ProcessInfo.processInfo.environment["OPENAI_API_KEY"] ?? "",
        model: Bundle.main.aiString(for: "OpenAIModel") ?? "gpt-4o-mini"
    )
}

private extension Bundle {
    func aiString(for key: String) -> String? {
        guard let value = object(forInfoDictionaryKey: key) as? String else { return nil }
        let trimmed = value.trimmingCharacters(in: .whitespacesAndNewlines)
        // Unresolved build-setting placeholders (e.g. "$(OPENAI_API_KEY)") are treated as missing.
        return trimmed.isEmpty || trimmed.hasPrefix("$(") ? nil : trimmed
    }
}

// MARK: - Structured Input / Output

struct AIForecastInput: Encodable {
    struct Vehicle: Encodable {
        let brand: String
        let model: String
        let engine: String
        let registrationYear: Int
        let currentMileageKm: Int
        let version: String?
        let color: String?
        let zone: String?
        let certifiedMaintenance: String?
        let numberOfOwners: Int?
        let optionals: [String]?

        init(_ car: UserCar) {
            brand = car.brand
            model = car.model
            engine = car.engine
            registrationYear = car.registrationYear
            currentMileageKm = car.actualKm
            version = car.version.forecastValue
            color = car.color.forecastValue
            zone = car.zone.forecastValue
            certifiedMaintenance = car.certifiedManintenance.forecastValue
            numberOfOwners = car.numberOfOwners
            optionals = car.optionals.isEmpty ? nil : car.optionals
        }
    }

    let schemaVersion = "2"
    let promptVersion = "2"
    let vehicle: Vehicle
    let referencePurchasePrice: Double
    let referencePriceSource = "application_dataset_or_technical_fallback_not_verified_market_quote"
    let valuationDate: String
    let valuationYear: Int
    let analysisYears: Int
    let startYear: Int
    let currencyCode = "EUR"
    let monetaryBasis = "constant_reference_euros_no_inflation_projection"
    let annualMileageKm: Int
    let annualMileageSource: String
    let missingParameters: [String]
    let marketEvidence: [String] = []
}

// Only the base curve is generated by the model. Scenario arithmetic belongs to the app.
struct AIForecastOutput: Decodable {
    let data: [DepreciationPoint]
}

// MARK: - Errors

enum AIForecastError: LocalizedError {
    case missingAPIKey
    case serviceUnavailable(statusCode: Int, details: String?)
    case invalidResponse(String)
    case requestFailed(String)

    var errorDescription: String? {
        switch self {
        case .missingAPIKey:
            return "Imposta la OpenAI API key in Info.plist (OpenAIAPIKey) oppure nella variabile OPENAI_API_KEY."
        case .serviceUnavailable(let statusCode, let details):
            let baseMessage = "OpenAI è temporaneamente sovraccarico (HTTP \(statusCode)). Riprova tra poco."
            guard let details, !details.isEmpty else { return baseMessage }
            return "\(baseMessage) Dettagli: \(details)"
        case .invalidResponse(let message):
            return "La risposta dell'AI non è valida: \(message)"
        case .requestFailed(let message):
            return message
        }
    }
}

// MARK: - Service

@MainActor
final class AIForecastService {
    private let client: OpenAIForecastClient

    init(configuration: AIServiceConfiguration = .current, session: URLSession? = nil) {
        self.client = OpenAIForecastClient(
            apiKey: configuration.apiKey,
            model: configuration.model,
            session: session ?? .forecasting
        )
    }

    func generateForecast(for userCar: UserCar, searchManager: SearchManager, years: Int = 20) async throws -> UserCarForecast {
        let now = Date()
        let currentYear = Calendar(identifier: .gregorian).component(.year, from: now)
        guard (1...50).contains(years), (1886...currentYear).contains(userCar.registrationYear),
              userCar.actualKm >= 0, userCar.numberOfOwners.map({ $0 > 0 }) ?? true,
              !userCar.brand.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              !userCar.model.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              !userCar.engine.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            throw AIForecastError.requestFailed("Parametri della previsione non validi.")
        }
        let engine = DepreciationEngine(searchManager: searchManager)
        let referencePrice = engine.resolvePurchasePrice(userCar: userCar)
        let policy = try ForecastScenarioAdjustment(userCar: userCar, searchManager: searchManager)
        guard referencePrice.isFinite, referencePrice > 0,
              policy.optimisticMultiplier.isFinite, policy.pessimisticMultiplier.isFinite else {
            throw AIForecastError.requestFailed("Prezzo o coefficienti della previsione non validi.")
        }
        let age = currentYear - userCar.registrationYear
        let fuel = engine.resolveCar(userCar: userCar).first.flatMap { car in
            searchManager.coefficientFuelTypes.first { $0.fuel == car.fuel }
        }
        let annualMileage = age > 0 ? userCar.actualKm / age : max(0, fuel?.averageKmByYears ?? engine.defaultFuel.averageKmByYears)
        let dateFormatter = DateFormatter()
        dateFormatter.locale = Locale(identifier: "en_US_POSIX")
        dateFormatter.calendar = Calendar(identifier: .gregorian)
        dateFormatter.dateFormat = "yyyy-MM-dd"
        let input = AIForecastInput(
            vehicle: .init(userCar), referencePurchasePrice: referencePrice,
            valuationDate: dateFormatter.string(from: now), valuationYear: currentYear,
            analysisYears: years, startYear: userCar.registrationYear,
            annualMileageKm: annualMileage,
            annualMileageSource: age > 0 ? "inferred_from_current_odometer_and_vehicle_age" : "fuel_dataset_or_technical_default",
            missingParameters: policy.missingParameters + (userCar.version.forecastValue == nil ? ["version"] : [])
        )
        let output = try await client.generateForecast(input: input)
        return try ForecastOutputValidator.makeForecast(output, input: input, userCar: userCar, adjustment: policy)
    }
}

/// Validate before publishing curves; do not silently drop duplicates, extra years or bad prices.
enum ForecastOutputValidator {
    static func makeForecast(_ output: AIForecastOutput, input: AIForecastInput, userCar: UserCar, adjustment: ForecastScenarioAdjustment) throws -> UserCarForecast {
        let expectedYears = Array(input.startYear...input.startYear + input.analysisYears)
        guard output.data.map(\.year) == expectedYears,
              output.data.allSatisfy({ $0.value.isFinite && $0.value >= 0 }) else {
            throw AIForecastError.invalidResponse("Serie base incompleta, non ordinata o con valori non validi.")
        }
        let optimistic = adjustment.optimisticSeries(from: output.data)
        let pessimistic = adjustment.pessimisticSeries(from: output.data)
        guard (optimistic + pessimistic).allSatisfy({ $0.value.isFinite && $0.value >= 0 }) else {
            throw AIForecastError.invalidResponse("Coefficienti degli scenari non validi.")
        }
        return UserCarForecast(
            userCar: userCar, data: output.data, optimisticData: optimistic,
            pessimisticData: pessimistic, purchasePrice: input.referencePurchasePrice,
            isExmample: false, isSaved: false
        )
    }
}

// MARK: - OpenAI client
private struct OpenAIForecastClient {
    let apiKey: String
    let model: String
    private let session: URLSession

    init(apiKey: String, model: String, session: URLSession = .forecasting) {
        self.apiKey = apiKey
        self.model = model
        self.session = session
    }

    func generateForecast(input: AIForecastInput) async throws -> AIForecastOutput {
        guard !apiKey.isEmpty else { throw AIForecastError.missingAPIKey }

        guard let url = URL(string: "https://api.openai.com/v1/chat/completions") else {
            throw AIForecastError.requestFailed("URL OpenAI non valida.")
        }

        let body = OpenAIChatRequest(
            model: model,
            messages: [
                .init(role: "system", content: ForecastPromptBuilder.systemPrompt),
                .init(role: "user", content: try ForecastPromptBuilder.makePrompt(for: input))
            ],
            temperature: 0.2,
            responseFormat: .init(pointCount: input.analysisYears + 1)
        )

        var request = URLRequest(url: url)
        request.httpMethod = "POST"
        request.setValue("Bearer \(apiKey)", forHTTPHeaderField: "Authorization")
        request.setValue("application/json", forHTTPHeaderField: "Content-Type")
        request.timeoutInterval = 120
        request.httpBody = try JSONEncoder().encode(body)

        let (data, response) = try await performRetriableRequest(request, session: session)
        try validateHTTPResponse(response, data: data)

        let apiResponse: OpenAIChatResponse
        do {
            apiResponse = try JSONDecoder().decode(OpenAIChatResponse.self, from: data)
        } catch {
            throw AIForecastError.invalidResponse("Formato della risposta API non riconosciuto.")
        }
        guard let choice = apiResponse.choices.first, choice.finishReason == "stop",
              choice.message.refusal == nil else {
            throw AIForecastError.invalidResponse("Generazione interrotta o rifiutata dal modello.")
        }
        guard let text = choice.message.content, !text.isEmpty else {
            throw AIForecastError.invalidResponse("OpenAI non ha restituito contenuto JSON.")
        }

        return try decodeAIForecastOutput(from: text)
    }
}

struct OpenAIChatRequest: Encodable {
    struct Message: Encodable {
        let role: String
        let content: String
    }

    struct ResponseFormat: Encodable {
        let pointCount: Int
        private enum CodingKeys: String, CodingKey { case type, jsonSchema = "json_schema" }
        private struct Definition: Encodable {
            let name = "vehicle_forecast_v2"
            let strict = true
            let schema: ForecastJSONSchema
        }
        func encode(to encoder: Encoder) throws {
            var container = encoder.container(keyedBy: CodingKeys.self)
            try container.encode("json_schema", forKey: .type)
            let point = ForecastJSONSchema.object([
                "year": .integer,
                "value": .number
            ])
            try container.encode(Definition(schema: .object([
                "data": .array(point, count: pointCount)
            ])), forKey: .jsonSchema)
        }
    }

    let model: String
    let messages: [Message]
    let temperature: Double
    let responseFormat: ResponseFormat

    enum CodingKeys: String, CodingKey {
        case model
        case messages
        case temperature
        case responseFormat = "response_format"
    }
}

private struct OpenAIChatResponse: Decodable {
    struct Choice: Decodable {
        struct Message: Decodable {
            let content: String?
            let refusal: String?
        }

        let message: Message
        let finishReason: String?
        enum CodingKeys: String, CodingKey { case message, finishReason = "finish_reason" }
    }

    let choices: [Choice]
}

