import Foundation

// MARK: - Structured Input / Output

struct AIForecastInput: Encodable {
    struct Vehicle: Encodable {
        let brand: String
        let model: String
        let engine: String
        let registrationYear: Int
        let currentMileageKm: Int
        let version: String?
        let color: String?
        let zone: String?
        let certifiedMaintenance: String?
        let numberOfOwners: Int?
        let optionals: [String]?

        init(_ car: UserCar) {
            brand = car.brand
            model = car.model
            engine = car.engine
            registrationYear = car.registrationYear
            currentMileageKm = car.actualKm
            version = car.version.forecastValue
            color = car.color.forecastValue
            zone = car.zone.forecastValue
            certifiedMaintenance = car.certifiedManintenance.forecastValue
            numberOfOwners = car.numberOfOwners
            optionals = car.optionals.isEmpty ? nil : car.optionals
        }
    }

    let vehicle: Vehicle
    let referencePurchasePrice: Double
    let analysisYears: Int
    let annualMileageKm: Int

    var startYear: Int { vehicle.registrationYear }

}

// Only the base curve is generated by the model. Scenario arithmetic belongs to the app.
struct AIForecastOutput: Decodable {
    let data: [DepreciationPoint]
}

// MARK: - Errors

enum AIForecastError: LocalizedError {
    case authenticationRequired
    case quotaExceeded
    case serviceUnavailable(statusCode: Int)
    case invalidResponse(String)
    case requestFailed(String)

    var errorDescription: String? {
        switch self {
        case .authenticationRequired:
            return AppLocalization.string("Accedi nuovamente per generare una previsione.")
        case .quotaExceeded:
            return AppLocalization.string("Hai raggiunto il limite di previsioni disponibili. Riprova più tardi.")
        case .serviceUnavailable(let statusCode):
            return AppLocalization.string("Il servizio di previsione è temporaneamente indisponibile (HTTP \(String(statusCode))). Riprova tra poco.")
        case .invalidResponse(let message):
            return AppLocalization.string("La risposta dell'AI non è valida: \(message)")
        case .requestFailed(let message):
            return message
        }
    }
}

// MARK: - Service

@MainActor
final class AIForecastService {
    typealias RequestForecast = @MainActor (AIForecastInput) async throws -> AIForecastOutput
    private let requestForecast: RequestForecast

    init(requestForecast: @escaping RequestForecast = SupabaseForecastClient.generateForecast) {
        self.requestForecast = requestForecast
    }

    func generateForecast(for userCar: UserCar, searchManager: SearchManager, years: Int = 20) async throws -> UserCarForecast {
        let now = Date()
        let currentYear = Calendar(identifier: .gregorian).component(.year, from: now)
        guard (1...50).contains(years), (1886...currentYear).contains(userCar.registrationYear),
              userCar.actualKm >= 0, userCar.numberOfOwners.map({ $0 > 0 }) ?? true,
              !userCar.brand.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              !userCar.model.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              !userCar.engine.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            throw AIForecastError.requestFailed(AppLocalization.string("Parametri della previsione non validi."))
        }
        let engine = DepreciationEngine(searchManager: searchManager)
        let referencePrice = engine.resolvePurchasePrice(userCar: userCar)
        let policy = try ForecastScenarioAdjustment(userCar: userCar, searchManager: searchManager)
        guard referencePrice.isFinite, referencePrice > 0,
              policy.optimisticMultiplier.isFinite, policy.pessimisticMultiplier.isFinite else {
            throw AIForecastError.requestFailed(AppLocalization.string("Prezzo o coefficienti della previsione non validi."))
        }
        let age = currentYear - userCar.registrationYear
        let fuel = engine.resolveCar(userCar: userCar).first.flatMap { car in
            searchManager.coefficientFuelTypes.first { $0.fuel == car.fuel }
        }
        let annualMileage = age > 0 ? userCar.actualKm / age : max(0, fuel?.averageKmByYears ?? engine.defaultFuel.averageKmByYears)
        let input = AIForecastInput(
            vehicle: .init(userCar), referencePurchasePrice: referencePrice,
            analysisYears: years, annualMileageKm: annualMileage
        )
        let output = try await requestForecast(input)
        return try ForecastOutputValidator.makeForecast(output, input: input, userCar: userCar, adjustment: policy)
    }
}

/// Validate before publishing curves; do not silently drop duplicates, extra years or bad prices.
enum ForecastOutputValidator {
    static func makeForecast(_ output: AIForecastOutput, input: AIForecastInput, userCar: UserCar, adjustment: ForecastScenarioAdjustment) throws -> UserCarForecast {
        let expectedYears = Array(input.startYear...input.startYear + input.analysisYears)
        guard output.data.map(\.year) == expectedYears,
              output.data.allSatisfy({ $0.value.isFinite && $0.value >= 0 }) else {
            throw AIForecastError.invalidResponse(AppLocalization.string("Serie base incompleta, non ordinata o con valori non validi."))
        }
        let optimistic = adjustment.optimisticSeries(from: output.data)
        let pessimistic = adjustment.pessimisticSeries(from: output.data)
        guard (optimistic + pessimistic).allSatisfy({ $0.value.isFinite && $0.value >= 0 }) else {
            throw AIForecastError.invalidResponse(AppLocalization.string("Coefficienti degli scenari non validi."))
        }
        return UserCarForecast(
            userCar: userCar, data: output.data, optimisticData: optimistic,
            pessimisticData: pessimistic, purchasePrice: input.referencePurchasePrice,
            isExmample: false, isSaved: false
        )
    }
}

// MARK: - Safe server errors

enum ForecastBackendError {
    static func map(statusCode: Int, data: Data) -> AIForecastError {
        // Do not display raw upstream error bodies, credentials or diagnostic payloads.
        struct Envelope: Decodable { let code: String? }
        let code = try? JSONDecoder().decode(Envelope.self, from: data).code
        switch statusCode {
        case 401, 403:
            return .authenticationRequired
        case 429 where code == "quota_exceeded":
            return .quotaExceeded
        case 400, 413:
            return .requestFailed(AppLocalization.string("I dati della previsione non sono validi."))
        case 404:
            return .requestFailed(AppLocalization.string("Il servizio di previsione non è ancora configurato."))
        case 422:
            return .invalidResponse(AppLocalization.string("Il servizio non ha potuto generare una curva valida."))
        default:
            return .serviceUnavailable(statusCode: statusCode)
        }
    }
}
